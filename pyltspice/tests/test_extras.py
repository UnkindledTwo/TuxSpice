"""TuxSpice extras: waveform measurements, plot export, vendor model import."""
import numpy as np
import pytest

from pyltspice.sim import libimport
from pyltspice.sim.wavemeasure import ac_measures, time_measures

from .conftest import needs_lib, needs_ngspice


def _m(rows):
    return {label: v for label, v, _ in rows}


def test_square_wave_measures():
    t = np.linspace(0, 1e-3, 5001)
    m = _m(time_measures(t, np.where((t * 10e3) % 1 < 0.3, 5.0, 0.0)))     # 10 kHz, 30 %
    assert m["Frequency"] == pytest.approx(10e3, rel=1e-3)
    assert m["Duty cycle"] == pytest.approx(30, abs=0.5)
    assert m["Maximum"] == 5 and m["Peak-to-peak"] == 5
    assert m["Average"] == pytest.approx(1.5, rel=0.01)


def test_step_overshoot_matches_second_order_theory():
    t = np.linspace(0, 1e-3, 5001)
    wn, z = 2 * np.pi * 20e3, 0.3
    wd = wn * np.sqrt(1 - z * z)
    y = 1 - np.exp(-z * wn * t) * (np.cos(wd * t) + z / np.sqrt(1 - z * z) * np.sin(wd * t))
    m = _m(time_measures(t, y))
    assert m["Overshoot"] == pytest.approx(100 * np.exp(-np.pi * z / np.sqrt(1 - z * z)), abs=0.05)
    assert m["Undershoot"] == 0
    assert 0 < m["Rise time 10-90%"] < 2e-5


def test_sine_has_frequency_but_no_edges():
    t = np.linspace(0, 1e-3, 4001)
    m = _m(time_measures(t, np.sin(2 * np.pi * 5e3 * t)))
    assert m["Frequency"] == pytest.approx(5e3, rel=1e-3)
    assert m["RMS"] == pytest.approx(1 / np.sqrt(2), rel=1e-3)
    assert "Rise time 10-90%" not in m and "Duty cycle" not in m


def test_ac_measures_lowpass_and_bandpass():
    f = np.logspace(1, 7, 1201)
    s = 2j * np.pi * f
    m = _m(ac_measures(f, 10 / (1 + s / (2 * np.pi * 1e3))))
    assert m["-3 dB high"] == pytest.approx(1e3, rel=0.01)
    assert m["Unity gain"] == pytest.approx(1e3 * np.sqrt(99), rel=0.01)
    assert "-3 dB low" not in m
    w0, q = 2 * np.pi * 10e3, 5
    m = _m(ac_measures(f, (s * w0 / q) / (s * s + s * w0 / q + w0 * w0)))
    assert m["Peak frequency"] == pytest.approx(10e3, rel=0.02)
    assert m["-3 dB high"] - m["-3 dB low"] == pytest.approx(10e3 / q, rel=0.03)


@needs_ngspice
def test_csv_export_all_steps_and_report_style_restores(qapp, tmp_path):
    import csv
    from pyltspice.sim.runner import Simulator
    from pyltspice.ui import plot_export
    from pyltspice.ui.waveform import WaveformViewer
    res = Simulator("* x\nV1 a 0 SIN(0 1 1k)\nR1 a b {R}\nC1 b 0 100n\n.step param R list 1k 2k\n"
                    ".tran 1m\n.end\n", tmp_path / "x").run()
    v = WaveformViewer(res.main_plot(), "x.raw")
    v.resize(500, 300)
    v.show()
    v.add_trace("V(b)")
    plot_export.write_csv(v, tmp_path / "d.csv")
    rows = list(csv.reader(open(tmp_path / "d.csv")))
    assert rows[0] == ["step", "time", "V(b)"]
    assert {r[0] for r in rows[1:]} == {"R=1K", "R=2K"}
    trace = v.panes[0].traces[0]
    pen = trace.items[0][1].opts["pen"].color().name()
    img = plot_export.render_image(v, 2, report=True)
    assert (img.width(), img.height()) == (2 * v.split.width(), 2 * v.split.height())
    assert img.pixelColor(5, 5).name() == "#ffffff"              # report background
    assert trace.items[0][1].opts["pen"].color().name() == pen    # screen colours are back
    assert plot_export.print_color(plot_export.QColor("#00ff00")).green() < 140
    v.close()


VENDOR = """* Vendor test library
* CONNECTIONS:   NON-INVERTING INPUT
*                | INVERTING INPUT
*                | | POSITIVE POWER SUPPLY
*                | | | NEGATIVE POWER SUPPLY
*                | | | | OUTPUT
*                | | | | |
.SUBCKT VOPA1    1 2 3 4 5
E1 6 0 1 2 1e5
R1 6 5 10
.ENDS VOPA1
* Ideal 2.5 V reference
.subckt VREF25 IN OUT GND params: V=2.5
V1 OUT GND {V}
R1 IN GND 1Meg
.ends
.model DTEST D(Is=1e-14 Rs=0.5)
"""


def test_scan_vendor_library(tmp_path):
    lib = tmp_path / "vendor.lib"
    lib.write_text(VENDOR)
    defs, encrypted = libimport.scan(lib)
    assert not encrypted
    op, ref, dio = defs
    assert op.labels[0] == "NON-INVERTING INPUT" and libimport.is_opamp(op)
    assert ref.pins == ["IN", "OUT", "GND"] and ref.params == "params: V=2.5" and not libimport.is_opamp(ref)
    assert dio.kind == "model" and dio.symbol == "diode"
    # outside the schematic's folder: AutoGenerated symbol, absolute model path
    name, attrs, asy, path = libimport.placement(ref, lib, tmp_path / "elsewhere" / "s.asc")
    assert name == "AutoGenerated\\\\VREF25" and f"SYMATTR ModelFile {lib.resolve()}" in asy
    (tmp_path / "enc.lib").write_bytes(b"<Binary File>\x00\x01")
    assert libimport.scan(tmp_path / "enc.lib") == ([], True)


@needs_lib
@needs_ngspice
def test_placed_vendor_parts_simulate(tmp_path):
    """Each kind of imported part, wired with net labels on its pins, netlists and runs."""
    from pyltspice.model.asc import Flag, Schematic, SymbolInst, Text
    from pyltspice.model.library import SymbolLibrary
    from pyltspice.model.netlist import generate_netlist, symbol_pins
    from pyltspice import config
    from pyltspice.sim.runner import Simulator
    folder = tmp_path / "My Designs"                  # a space in the path, as vendors' folders have
    folder.mkdir()
    lib = folder / "vendor.lib"
    lib.write_text(VENDOR)
    sch_path = folder / "t.asc"
    op, ref, dio = libimport.scan(lib)[0]
    sym_lib = SymbolLibrary([config.SYM_DIR])
    items, x = [], 0
    nets = {"VOPA1": ["in", "out", "vp", "0", "out"], "VREF25": ["vp", "ref", "0"], "DTEST": ["vp", "dk"]}
    for k, d in enumerate((op, ref, dio)):
        name, attrs, asy, asy_path = libimport.placement(d, lib, sch_path)
        if asy:
            asy_path.write_text(asy)
            assert asy_path.parent == folder and "SYMATTR ModelFile vendor.lib" in asy
        inst = SymbolInst(name, x, 0, "R0", {}, {"InstName": f"U{k}", **attrs})
        sym = sym_lib.get(name, [folder])
        pins = sorted(symbol_pins(inst, sym), key=lambda p: p.pin.order)
        items += [inst] + [Flag(*p.point, n) for p, n in zip(pins, nets[d.name])]
        x += 400
    items += [Text(0, 400, "Left", 2, "!Vp vp 0 5\\nVin in 0 1.2\\nRd dk 0 1k\\n.op")]
    sch = Schematic(items=items, path=sch_path)
    nl = generate_netlist(sch, sym_lib)
    assert not nl.errors, nl.errors
    assert ".lib vendor.lib" in nl.text.splitlines()
    res = Simulator(nl.text, tmp_path / "run", [folder]).run()
    assert res.ok, res.errors
    op_plot = res.plots[0]
    v = {var.name.lower(): float(np.real(op_plot.data[var.index][0])) for var in op_plot.variables}
    assert v["v(out)"] == pytest.approx(1.2, abs=1e-3)     # follower
    assert v["v(ref)"] == pytest.approx(2.5, abs=1e-6)
    assert 3.5 < v["v(dk)"] < 4.6                           # 5 V through the diode into 1k


